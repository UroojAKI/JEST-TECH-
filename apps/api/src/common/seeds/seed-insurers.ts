export async function seedInsurers(client: PrismaClient) {
  let count = 0;
  for (const item of CANONICAL_MOTOR_INSURERS) {
    const insurer = await client.insurer.upsert({
      where: { code: item.code },
      update: {
        name: item.name,
        irdaiRegistrationNumber: item.irdaiRegistrationNumber,
        contactEmail: item.contactEmail,
        contactPhone: item.contactPhone,
        rating: item.rating,
        supportsZeroDep: item.supportsZeroDep ?? true,
        supportsRTI: item.supportsRTI ?? true,
        supportsEngineProtect: item.supportsEngineProtect ?? true,
        supportsRSA: item.supportsRSA ?? true,
        supportsNCBProtection: item.supportsNCBProtection ?? true,
        supportsConsumables: item.supportsConsumables ?? true,
        supportsKeyProtect: item.supportsKeyProtect ?? true,
        supportsTyreProtect: item.supportsTyreProtect ?? true,
        isActive: true,
      },
      create: {
        name: item.name,
        code: item.code,
        irdaiRegistrationNumber: item.irdaiRegistrationNumber,
        contactEmail: item.contactEmail,
        contactPhone: item.contactPhone,
        rating: item.rating,
        supportsZeroDep: item.supportsZeroDep ?? true,
        supportsRTI: item.supportsRTI ?? true,
        supportsEngineProtect: item.supportsEngineProtect ?? true,
        supportsRSA: item.supportsRSA ?? true,
        supportsNCBProtection: item.supportsNCBProtection ?? true,
        supportsConsumables: item.supportsConsumables ?? true,
        supportsKeyProtect: item.supportsKeyProtect ?? true,
        supportsTyreProtect: item.supportsTyreProtect ?? true,
        isActive: true,
      },
    });

    const defaultProducts = [
      { code: `${item.code}_COMPREHENSIVE`, productName: `${item.name} Comprehensive Motor`, policyType: 'COMPREHENSIVE', vehicleType: 'FOUR_WHEELER' },
      { code: `${item.code}_TP_ONLY`, productName: `${item.name} Third Party Liability Only`, policyType: 'TP_ONLY', vehicleType: 'FOUR_WHEELER' },
      { code: `${item.code}_SAOD`, productName: `${item.name} Standalone Own Damage`, policyType: 'SAOD', vehicleType: 'FOUR_WHEELER' },
    ];

    for (const p of defaultProducts) {
      await client.insuranceProduct.upsert({
        where: { code: p.code },
        update: {
          productName: p.productName,
          policyType: p.policyType,
          vehicleType: p.vehicleType,
          isActive: true,
        },
        create: {
          insurerId: insurer.id,
          code: p.code,
          productName: p.productName,
          policyType: p.policyType,
          vehicleType: p.vehicleType,
          isActive: true,
        },
      });
    }

    count++;
  }

  return count;
}

